#!/usr/bin/env python3
"""Generate docs/reference/*.md from the backend policy files.

The tables are derived from the same JSON the on-device backend loads, so
rerun this after changing a policy:

    python3 scripts/generate_docs_tables.py
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
POLICY = ROOT / 'server/policy'
OUT = ROOT / 'docs/reference'
sys.path.insert(0, str(ROOT))

from server.account_progression import level_state  # noqa: E402
from server.difficulty_rewards import load_policy as difficulty_policy  # noqa: E402

DIFFICULTY_CODES = {'B': 0, 'A': 1, 'S': 2, 'P': 3, 'W': 4, 'L': 5, 'U': 6}
BANDS = ('RELEGATION', 'MAINTENANCE', 'PROMOTION', 'CHAMPIONSHIP')
BAND_NAMES = {
    'RELEGATION': 'Relegation',
    'MAINTENANCE': 'Stay up',
    'PROMOTION': 'Promotion',
    'CHAMPIONSHIP': 'Title',
}
HEADER = '<!-- Generated by scripts/generate_docs_tables.py; do not edit by hand. -->\n\n'


def load(name):
    return json.loads((POLICY / name).read_text())


def coins(value):
    if value is None:
        return '—'
    return f'{value:,}'


def table(headers, rows):
    lines = ['| ' + ' | '.join(headers) + ' |']
    lines.append('|' + '|'.join('---' for _ in headers) + '|')
    for row in rows:
        lines.append('| ' + ' | '.join(str(cell) for cell in row) + ' |')
    return '\n'.join(lines) + '\n'


def pack_names():
    definitions = load('pack-definitions.json')['definitions']
    names = {}
    for key, value in definitions.items():
        name = value.get('name', key)
        if name.isupper():
            name = name.title()
        names[key] = name
    return names


def store_packs():
    definitions = load('pack-definitions.json')['definitions']
    bindings = load('reward-store-parity-v1.json')['bindings']
    prices = load('offline-rewards-v1.json')['permanent_coin_catalog']
    points = load('store-fp-prices-fifa16-console-v1.json')['point_prices']
    rows = []
    for label, binding in bindings.items():
        rule = definitions[binding['definition']]
        rows.append([
            label, rule['item_count'], rule['quality'].title(), rule['minimum_rare'],
            coins(prices[label]['coin_price']), coins(points.get(label)),
        ])
    return rows


def rule_text(rule, competition):
    operator = {'>=': 'at least', '==': 'exactly'}[rule['operator']]
    kind = rule['kind']
    if kind == 'chemistry':
        return f'Chemistry {operator} {rule["value"]}'
    if kind == 'distinct_nationalities':
        return f'{operator.capitalize()} {rule["value"]} nationalities in the starting XI'
    if kind == 'players_sharing_league':
        return f'{operator.capitalize()} {rule["value"]} starters from one league'
    if kind == 'players_from_named_league':
        return f'{operator.capitalize()} {rule["value"]} starters from {competition}'
    raise ValueError('Unknown rule kind ' + kind)


def season_coins(policy, codes, band):
    counts = [0] * 7
    for code in codes:
        counts[DIFFICULTY_CODES[code]] += 1
    total = 0
    for difficulty, count in enumerate(counts):
        amount = policy['tiers'][str(difficulty)]['season_coins'][band]
        if count and amount is None:
            return None
        total += count * (amount or 0)
    return total // sum(counts)


def seasons_page():
    difficulty = difficulty_policy()
    thresholds = load('offline-seasons-revival.json')['divisions']
    rewards = load('offline-rewards-v1.json')['divisions']
    choices = load('offline-season-choices-v1.json')['competitions']
    labels = {str(i): row['label'] for i, row in difficulty['tiers'].items()}
    letters = {code: labels[str(i)] for code, i in DIFFICULTY_CODES.items()}

    out = [HEADER, '# Seasons reference\n\n']
    out.append('## Points needed per division\n\n')
    out.append('A season is 10 matches: win 3 points, draw 1, loss 0. ')
    out.append('Final points decide the outcome. "—" means the outcome does not exist '
               'in that division.\n\n')
    rows = []
    for division in range(10, 0, -1):
        row = thresholds[str(division)]
        relegation = '—' if row['maintenance'] == 0 else f'below {row["maintenance"]}'
        promotion = '—' if row['promotion'] is None else row['promotion']
        rows.append([division, relegation, row['maintenance'], promotion, row['championship']])
    out.append(table(['Division', 'Relegated', 'Stay up', 'Promotion', 'Title'], rows))

    out.append('\n## Match and title packs per division\n\n')
    out.append('Every Seasons match also drops one untradeable pack chosen by result. '
               'Winning the title adds one more pack.\n\n')
    rows = []
    for division in range(10, 0, -1):
        row = rewards[str(division)]
        rows.append([division, row['match']['W']['pack_label'], row['match']['D']['pack_label'],
                     row['match']['L']['pack_label'], row['season']['CHAMPIONSHIP']['pack_label']])
    out.append(table(['Division', 'Win pack', 'Draw pack', 'Loss pack', 'Title pack'], rows))

    out.append('\n## Competitions\n\n')
    out.append('Each division offers several competitions. Their 10 fixtures have fixed '
               'difficulties, shown as letters: ')
    out.append(', '.join(f'**{code}** {name}' for code, name in letters.items()) + '. ')
    out.append('End-of-season coins are the average of the difficulty table over all '
               '10 scheduled fixtures, rounded down.\n\n')
    for division in range(10, 0, -1):
        out.append(f'### Division {division}\n\n')
        rows = []
        for competition in choices:
            if competition['division'] != division:
                continue
            requirements = '; '.join(rule_text(r, competition['name'])
                                     for r in competition['rules']) or 'None'
            amounts = [coins(season_coins(difficulty, competition['difficulty_codes'], band))
                       for band in BANDS]
            if division == 10:
                amounts[0] = '—'
            if division == 1:
                amounts[2] = '—'
            rows.append([competition['name'], f'`{competition["difficulty_codes"]}`',
                         requirements, *amounts])
        out.append(table(['Competition', 'Fixtures', 'Squad requirement',
                          *(BAND_NAMES[b] + ' coins' for b in BANDS)], rows))
        out.append('\n')
    return ''.join(out)


def difficulty_page():
    policy = difficulty_policy()
    out = [HEADER, '# Difficulty rewards\n\n']
    out.append('Seasons and Tournaments pay match coins and XP by the difficulty of '
               'the fixture. Coins below are for account level 1; each level above 1 '
               'adds 2% (level 10 earns 118%). XP is the base (win 100, draw 60, '
               'loss 30) times the XP scale.\n\n')
    rows = []
    for i in range(7):
        tier = policy['tiers'][str(i)]
        match = tier['match_coins']
        xp = {r: policy['xp_base'][r] * tier['xp_scale_percent'] // 100 for r in 'WDL'}
        rows.append([tier['label'], coins(match['W']), coins(match['D']), coins(match['L']),
                     f'{tier["xp_scale_percent"]}%', xp['W'], xp['D'], xp['L']])
    out.append(table(['Difficulty', 'Win coins', 'Draw coins', 'Loss coins', 'XP scale',
                      'Win XP', 'Draw XP', 'Loss XP'], rows))
    out.append('\n## Season coins by difficulty\n\n')
    out.append('A season pays the average of these values over its 10 scheduled '
               'fixtures (see [Seasons](seasons.md) for each competition).\n\n')
    rows = []
    for i in range(7):
        tier = policy['tiers'][str(i)]
        rows.append([tier['label'], *(coins(tier['season_coins'][b]) for b in BANDS)])
    out.append(table(['Difficulty', *(BAND_NAMES[b] for b in BANDS)], rows))
    return ''.join(out)


def tournaments_page():
    catalog = load('offline-tournament-catalog-v2.json')
    rewards = load('tournament-rewards-v2.json')
    difficulty = difficulty_policy()
    names = pack_names()
    labels = {i: row['label'] for i, row in difficulty['tiers'].items()}
    match_packs = load('offline-rewards-v1.json')['divisions']
    out = [HEADER, '# Tournaments reference\n\n']
    out.append(f'Every cup is a 16-team knockout: {catalog["rounds"]} rounds, '
               f'{catalog["match_minutes"]}-minute matches. Lose once and the run ends.\n\n')
    rows = []
    for cup in catalog['cups']:
        sid = str(cup['service_id'])
        requirements = []
        if cup['required_quality']:
            requirements.append(f'{cup["required_quality"].title()} players only (XI and subs)')
        if cup['minimum_chemistry']:
            requirements.append(f'Chemistry at least {cup["minimum_chemistry"]}')
        if cup['minimum_brazilian_starters']:
            requirements.append(f'At least {cup["minimum_brazilian_starters"]} Brazilian starters')
        prize = rewards['championship'][sid]
        packs = ' + '.join(names.get(p, p) for p in prize['first_win_packs'])
        rows.append([cup['name'], labels[str(cup['difficulty'])],
                     '; '.join(requirements) or 'None', coins(prize['coins']), packs])
    out.append(table(['Cup', 'Difficulty', 'Squad requirement', 'Winner coins (every win)',
                      'First-win bonus (once per cup)'], rows))
    out.append('\n## Match rewards\n\n')
    out.append('Each tournament match pays the [difficulty](difficulty.md) coins and XP '
               'for the cup\'s difficulty, plus one untradeable pack from the Seasons '
               'match-pack table of the division listed here.\n\n')
    rows = []
    for tier, division in rewards['match_pack_divisions'].items():
        row = match_packs[str(division)]['match']
        rows.append([labels[tier], division, row['W']['pack_label'], row['D']['pack_label'],
                     row['L']['pack_label']])
    out.append(table(['Difficulty', 'Pack table of division', 'Win pack', 'Draw pack',
                      'Loss pack'], rows))
    return ''.join(out)


def progression_page():
    levels = load('level-rewards-v1.json')
    welcome = load('welcome-gift-v1.json')['grant']
    starter = load('first-run-starter-v1.json')
    names = pack_names()
    out = [HEADER, '# Progression reference\n\n']
    out.append('## Levels\n\n')
    out.append('Reaching level 2 takes 300 XP; each further level takes 50 XP more '
               f'than the one before. Each level-up pays {levels["coins_per_level"]:,} coins times the '
               'new level. Milestone packs are untradeable.\n\n')
    rows = []
    for level in range(2, 31):
        spent = 25 * (level - 1) ** 2 + 275 * (level - 1)
        assert level_state(spent)['level'] == level
        pack = levels['milestone_packs'].get(str(level))
        if pack is None and level >= levels['repeat_from_level'] and level % 5 == 0:
            pack = levels['repeat_pack']
        rows.append([level, coins(spent), coins(levels['coins_per_level'] * level),
                     names.get(pack, '') if pack else ''])
    out.append(table(['Level', 'Total XP', 'Level-up coins', 'Milestone pack'], rows))
    out.append(f'\nAfter level 30, every 5th level repeats the '
               f'{names[levels["repeat_pack"]]}.\n')
    out.append('\n## New club\n\n')
    out.append(table(['Grant', 'Contents'], [
        ['Starting squad', f'{starter["starting"]["favourite_club"]} gold from your favourite '
         f'club (silver/bronze if none), {starter["starting"]["silver"]} silver, '
         f'{starter["starting"]["bronze"]} bronze starters; '
         f'{starter["bench"]["silver"]} silver and {starter["bench"]["bronze"]} bronze subs'],
        ['Manager', f'Random {starter["manager_quality"]} manager'],
        ['Club items', starter['club_items']],
        ['Welcome gift', f'{welcome["coins"]:,} coins and {welcome["packs"]["count"]} untradeable '
         f'{names[welcome["packs"]["definition"]]}s, claimed from the welcome message'],
    ]))
    return ''.join(out)


def accomplishments_page():
    value = load('accomplishments-v1.json')
    categories = {c['id']: c['name'] for c in value['categories']}
    out = [HEADER, '# Accomplishments reference\n\n']
    out.append('Progress counts from the moment a club is created (no back pay). '
               'Collect finished challenges with **Redeem**. Packs and cards are '
               'untradeable.\n\n')
    for category_id, name in categories.items():
        out.append(f'## {name}\n\n')
        rows = []
        for challenge in value['challenges']:
            if challenge['category'] != category_id:
                continue
            reward = challenge['reward']
            parts = []
            if reward.get('coins'):
                parts.append(f'{reward["coins"]:,} coins')
            if reward.get('pack'):
                parts.append(f'{reward["pack"]} pack')
            if reward.get('card'):
                parts.append('special card (see description)')
            rows.append([challenge['name'], challenge['description'], ' + '.join(parts)])
        out.append(table(['Challenge', 'Goal', 'Reward'], rows))
        out.append('\n')
    return ''.join(out)


def store_page():
    offers = load('store-demo-offers-v1.json')['offers']
    out = [HEADER, '# Store and packs reference\n\n']
    out.append('All packs can contain specials. The same packs are used as match, '
               'title, level and accomplishment rewards (untradeable when earned).\n\n')
    out.append(table(['Pack', 'Items', 'Quality', 'Guaranteed rares', 'Coins', 'FIFA Points'],
                     store_packs()))
    out.append('\n## Special offers\n\n')
    rows = []
    for offer in offers:
        captions = offer['captions']
        rows.append([captions['NAME'].title(), captions['DESC'], coins(offer['coin_price'])])
    out.append(table(['Offer', 'Contents', 'Coins'], rows))
    return ''.join(out)


def market_page():
    market = load('market-economy-v1.json')
    quick = load('quick-sell-fifa16-approx-v1.json')['player_multipliers']
    out = [HEADER, '# Transfer Market and quick sell reference\n\n']
    out.append('The Transfer Market is simulated locally: about '
               f'{market["supply"]["inventory_size"]} computer listings at a time, most '
               'listed for one hour. Your listings sell to simulated buyers; '
               f'a {market["fee_percent"]}% fee is taken from each sale.\n\n')
    price = market['price']
    out.append(table(['Rule', 'Value'], [
        ['Price range', f'{coins(price["minimum"])} – {coins(price["maximum"])} coins'],
        ['Non-special bronze/silver cap', f'{coins(price["card_maximum"]["bronze"])} coins'],
        ['Sale chance at ≤90% of fair price',
         f'{market["demand"]["gold"]}%'],
        ['Instant sale', f'Priced ≤{market["sale"]["instant_below_percent"]}% of fair: '
         f'sells in {market["sale"]["instant_seconds"][0]}–'
         f'{market["sale"]["instant_seconds"][1]} s'],
    ]))
    out.append('\n## Quick sell (players)\n\n')
    out.append('Quick sell pays rating × factor, rounded half up. Earned '
               '(untradeable) items quick sell for 0.\n\n')
    rows = []
    for quality, values in quick.items():
        rows.append([quality.title(), *(f'{n}/{d}' for n, d in
                                        (values['common'], values['rare'], values['special']))])
    out.append(table(['Quality', 'Common', 'Rare', 'Special'], rows))
    return ''.join(out)


PAGES = {
    'seasons.md': seasons_page,
    'difficulty.md': difficulty_page,
    'tournaments.md': tournaments_page,
    'progression.md': progression_page,
    'accomplishments.md': accomplishments_page,
    'store.md': store_page,
    'market.md': market_page,
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, render in PAGES.items():
        (OUT / name).write_text(render())
        print(OUT / name)


if __name__ == '__main__':
    main()
